#!/usr/bin/env python3
"""
Wildcards: page sections built locally, with no API call and no tokens spent.

Each wildcard is a function that takes an ISO date string and returns
(title, body_html). It must be deterministic — the same date always produces
the same output — so that an archived page keeps its puzzle forever.

Adding another one (kakuro, nonogram, cryptogram) is a three-step job:

    @wildcard("kakuro")
    def kakuro(date_iso):
        ...
        return "Kakuro", body_html

...then list its key under `wildcards:` in prompts.yaml. Nothing in
generate.py needs to change.
"""

import math
import random
from datetime import datetime

# --------------------------------------------------------------------------
# Registry
# --------------------------------------------------------------------------
REGISTRY = {}


def wildcard(key):
    def deco(fn):
        REGISTRY[key] = fn
        return fn
    return deco


def seeded_rng(date_iso, salt=""):
    """A random generator pinned to the date, so output is reproducible."""
    return random.Random(f"{date_iso}|{salt}")


def pick(date_iso, keys, count=1):
    """Choose `count` wildcard keys for this date, cycling evenly through them."""
    keys = [k for k in keys if k in REGISTRY]
    if not keys or count <= 0:
        return []
    day = datetime.strptime(date_iso, "%Y-%m-%d").timetuple().tm_yday
    start = (day * count) % len(keys)
    return [keys[(start + i) % len(keys)] for i in range(min(count, len(keys)))]


def build(key, date_iso):
    return REGISTRY[key](date_iso)


# ==========================================================================
# SHIKAKU
#
# Partition a grid into rectangles; each holds exactly one number equal to
# its area. Generated by recursive splitting, then verified to have exactly
# one solution — a puzzle with two solutions isn't a puzzle.
# ==========================================================================
ROWS, COLS = 7, 7


def _split(r0, c0, h, w, rng, out):
    """Recursively cut a block into rectangles of a pleasant size."""
    area = h * w
    small_enough = area <= 8
    must_stop = h == 1 and w == 1

    if must_stop or (small_enough and (area <= 3 or rng.random() < 0.5)):
        out.append((r0, c0, h, w))
        return

    ways = []
    if h > 1:
        ways.append("h")
    if w > 1:
        ways.append("v")
    if not ways:
        out.append((r0, c0, h, w))
        return

    for _ in range(6):
        way = rng.choice(ways)
        if way == "h":
            cut = rng.randint(1, h - 1)
            a, b = (r0, c0, cut, w), (r0 + cut, c0, h - cut, w)
        else:
            cut = rng.randint(1, w - 1)
            a, b = (r0, c0, h, cut), (r0, c0 + cut, h, w - cut)
        if a[2] * a[3] >= 2 and b[2] * b[3] >= 2:
            _split(*a, rng, out)
            _split(*b, rng, out)
            return

    out.append((r0, c0, h, w))


def _candidates(r, c, area, clue_cells):
    """Every rectangle of the right area that covers (r,c) and no other clue."""
    out = []
    for h in range(1, ROWS + 1):
        if area % h:
            continue
        w = area // h
        if w > COLS:
            continue
        for top in range(max(0, r - h + 1), min(r, ROWS - h) + 1):
            for left in range(max(0, c - w + 1), min(c, COLS - w) + 1):
                if not (top <= r < top + h and left <= c < left + w):
                    continue
                clues_inside = sum(
                    1 for (cr, cc) in clue_cells
                    if top <= cr < top + h and left <= cc < left + w
                )
                if clues_inside == 1:
                    out.append((top, left, h, w))
    return out


def _count_solutions(clues, limit=2):
    """Exact-cover backtracking. Stops as soon as `limit` solutions are found."""
    clue_cells = [(r, c) for (r, c, _) in clues]
    cands = {
        (r, c): _candidates(r, c, a, clue_cells)
        for (r, c, a) in clues
    }
    # Most-constrained clue first keeps the search small.
    order = sorted(cands, key=lambda k: len(cands[k]))
    grid = [[False] * COLS for _ in range(ROWS)]
    found = [0]
    layout = []

    def place(rect, val):
        top, left, h, w = rect
        for rr in range(top, top + h):
            for cc in range(left, left + w):
                grid[rr][cc] = val

    def fits(rect):
        top, left, h, w = rect
        for rr in range(top, top + h):
            for cc in range(left, left + w):
                if grid[rr][cc]:
                    return False
        return True

    def recurse(i, acc):
        if found[0] >= limit:
            return
        if i == len(order):
            found[0] += 1
            if found[0] == 1:
                layout.extend(acc)
            return
        key = order[i]
        for rect in cands[key]:
            if fits(rect):
                place(rect, True)
                acc.append(rect)
                recurse(i + 1, acc)
                acc.pop()
                place(rect, False)
                if found[0] >= limit:
                    return

    recurse(0, [])
    return found[0], layout


def make_shikaku(date_iso, max_attempts=60):
    """Return (clues, solution_rects). Retries until the puzzle is unique."""
    for attempt in range(max_attempts):
        rng = seeded_rng(date_iso, f"shikaku-{attempt}")
        rects = []
        _split(0, 0, ROWS, COLS, rng, rects)
        if len(rects) < 6:
            continue

        clues = []
        for (top, left, h, w) in rects:
            cells = [(top + i, left + j) for i in range(h) for j in range(w)]
            r, c = rng.choice(cells)
            clues.append((r, c, h * w))

        n, layout = _count_solutions(clues, limit=2)
        if n == 1:
            return clues, layout
    raise RuntimeError(f"no unique shikaku for {date_iso}")


def _grid_svg(clues, solution=None, interactive=False):
    cell, pad = 42, 6
    w = COLS * cell + pad * 2
    h = ROWS * cell + pad * 2
    cls = "pz-board" if interactive else "pz-svg"
    parts = [
        f'<svg viewBox="0 0 {w} {h}" class="{cls}" role="img" '
        f'aria-label="Shikaku grid, {ROWS} by {COLS}">'
    ]
    if interactive:
        parts.append('<g class="pz-shapes"></g>')
    parts.append(
        f'<rect x="{pad}" y="{pad}" width="{COLS*cell}" height="{ROWS*cell}" '
        f'fill="none" stroke="var(--ink)" stroke-width="2"/>'
    )
    for i in range(1, COLS):
        x = pad + i * cell
        parts.append(f'<line x1="{x}" y1="{pad}" x2="{x}" y2="{pad+ROWS*cell}" '
                     f'stroke="var(--hair)" stroke-width="1"/>')
    for i in range(1, ROWS):
        y = pad + i * cell
        parts.append(f'<line x1="{pad}" y1="{y}" x2="{pad+COLS*cell}" y2="{y}" '
                     f'stroke="var(--hair)" stroke-width="1"/>')

    if solution:
        for (top, left, rh, rw) in solution:
            parts.append(
                f'<rect x="{pad+left*cell+2}" y="{pad+top*cell+2}" '
                f'width="{rw*cell-4}" height="{rh*cell-4}" fill="none" '
                f'stroke="var(--accent)" stroke-width="2.5" rx="3"/>'
            )

    for (r, c, a) in clues:
        parts.append(
            f'<text x="{pad+c*cell+cell/2}" y="{pad+r*cell+cell/2}" '
            f'text-anchor="middle" dominant-baseline="central" '
            f'class="pz-num">{a}</text>'
        )
    parts.append("</svg>")
    return "".join(parts)


