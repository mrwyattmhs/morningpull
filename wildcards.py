def _factorize(n):
    out, d, m = [], 2, n
    while d * d <= m:
        while m % d == 0:
            out.append(d)
            m //= d
        d += 1
    if m > 1:
        out.append(m)
    return out


def _facts(n):
    f = []
    if n == 1:
        return ["The multiplicative identity — the only number that is neither "
                "prime nor composite.",
                "A perfect square, a triangular number, and a factorial, all at once.",
                "In binary it's 1; in hex, 1."]

    primes = _factorize(n)
    if len(primes) == 1:
        f.append("It's prime.")
    else:
        grouped, seen = [], {}
        for p in primes:
            seen[p] = seen.get(p, 0) + 1
        for p in sorted(seen):
            grouped.append(f"{p}<sup>{seen[p]}</sup>" if seen[p] > 1 else str(p))
        f.append("Factors as " + " × ".join(grouped) + ".")

    r = math.isqrt(n)
    if r * r == n:
        f.append(f"A perfect square — {r}².")
    t = (math.isqrt(8 * n + 1) - 1) / 2
    if t == int(t):
        f.append(f"A triangular number: the sum of 1 through {int(t)}.")
    if n > 1 and (n & (n - 1)) == 0:
        f.append(f"A power of two — 2<sup>{n.bit_length()-1}</sup>.")

    divisors = [d for d in range(1, n) if n % d == 0]
    s = sum(divisors)
    if s == n:
        f.append("Perfect: its proper divisors sum to itself.")
    elif s > n:
        f.append(f"Abundant — its divisors sum to {s}, more than itself.")
    else:
        f.append(f"Deficient — its divisors sum to {s}.")

    f.append(f"In binary it's {n:b}; in hex, {n:X}.")
    if len(divisors) + 1 > 6:
        f.append(f"It has {len(divisors)+1} divisors in total.")
    return f


@wildcard("numbers")
def numbers(date_iso):
    d = datetime.strptime(date_iso, "%Y-%m-%d")
    n = d.timetuple().tm_yday
    items = "".join(f"<li>{x}</li>" for x in _facts(n))
    body = (
        f'<p class="wc-lead">Day <strong>{n}</strong> of the year.</p>'
        f'<ul class="wc-facts">{items}</ul>'
    )
    return f"Number {n}", body
