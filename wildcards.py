@wildcard("shikaku")
def shikaku(date_iso):
    clues, solution = make_shikaku(date_iso)
    uid = "pz-" + date_iso.replace("-", "")
    cell, pad = 42, 6
    vw = COLS * cell + pad * 2
    vh = ROWS * cell + pad * 2

    js = PZ_JS % {
        "uid": uid, "date": date_iso, "rows": ROWS, "cols": COLS,
        "cell": cell, "pad": pad, "vw": vw, "vh": vh,
        "clues": "[" + ",".join(f"[{r},{c},{a}]" for (r, c, a) in clues) + "]",
    }

    body = (
        PZ_CSS
        + '<p class="pz-rule">Divide the grid into rectangles. Every rectangle '
        'holds exactly one number, and that number is how many squares it '
        'covers. Drag to draw a rectangle; tap one to remove it.</p>'
        + f'<div class="pz-wrap" id="{uid}">'
        + _grid_svg(clues, interactive=True)
        + '<div class="pz-bar">'
        '<button type="button" class="pz-btn pz-clear">Clear</button>'
        '<span class="pz-status">0 of 49 squares</span>'
        "</div>"
        + '<details class="pz-reveal"><summary>Show solution</summary>'
        + _grid_svg(clues, solution)
        + "</details>"
        + "</div>"
        + js
    )
    return "Shikaku", body


