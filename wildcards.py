def _fretboard_svg(root_idx, intervals):
    left, top = 34, 26
    fw, sh = 46, 26
    w = left + FRETS * fw + 26
    h = top + (len(STRINGS) - 1) * sh + 34
    tones = {(root_idx + i) % 12 for i in intervals}

    p = [f'<svg viewBox="0 0 {w} {h}" class="fb-svg" role="img" '
         f'aria-label="Fretboard diagram">']

    for i in range(FRETS + 1):
        x = left + i * fw
        width = 3 if i == 0 else 1
        p.append(f'<line x1="{x}" y1="{top}" x2="{x}" y2="{top+(len(STRINGS)-1)*sh}" '
                 f'stroke="var(--ink)" stroke-width="{width}" opacity="0.55"/>')
    for i in range(len(STRINGS)):
        y = top + i * sh
        p.append(f'<line x1="{left}" y1="{y}" x2="{left+FRETS*fw}" y2="{y}" '
                 f'stroke="var(--muted)" stroke-width="1"/>')
    for f in (3, 5, 7, 9, 12):
        p.append(f'<text x="{left+f*fw-fw/2}" y="{top+(len(STRINGS)-1)*sh+22}" '
                 f'text-anchor="middle" class="fb-mark">{f}</text>')

    for si, sname in enumerate(STRINGS):
        open_idx = NOTES.index(sname)
        y = top + si * sh
        p.append(f'<text x="{left-14}" y="{y}" text-anchor="middle" '
                 f'dominant-baseline="central" class="fb-mark">{sname}</text>')
        for fret in range(FRETS + 1):
            n = (open_idx + fret) % 12
            if n not in tones:
                continue
            x = left + (fret * fw if fret == 0 else fret * fw - fw / 2)
            is_root = n == root_idx
            fill = "var(--accent)" if is_root else "var(--paper)"
            stroke = "var(--accent)" if is_root else "var(--ink)"
            tcls = "fb-dot-root" if is_root else "fb-dot-note"
            p.append(f'<circle cx="{x}" cy="{y}" r="10" fill="{fill}" '
                     f'stroke="{stroke}" stroke-width="1.5"/>')
            p.append(f'<text x="{x}" y="{y}" text-anchor="middle" '
                     f'dominant-baseline="central" class="{tcls}">{NOTES[n]}</text>')
    p.append("</svg>")
    return "".join(p)


@wildcard("music")
def music(date_iso):
    rng = seeded_rng(date_iso, "music")
    root = rng.choice(NOTES)
    name, intervals, blurb = rng.choice(SCALES)
    drill = rng.choice(DRILLS)
    root_idx = NOTES.index(root)
    notes = " · ".join(NOTES[(root_idx + i) % 12] for i in intervals)

    body = (
        f'<p class="wc-lead"><strong>{root} {name}</strong> — {blurb}</p>'
        f'<p class="wc-notes">{notes}</p>'
        + _fretboard_svg(root_idx, intervals)
        + f'<p class="wc-drill"><span class="wc-drill-label">Drill</span> {drill}</p>'
    )
    return "Fretboard", body


